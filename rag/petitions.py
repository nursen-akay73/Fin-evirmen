def classify_petition(topic: str, clause: str = "") -> str:
    blob = f"{topic} {clause}".lower()
    aidat = any(word in blob for word in ("aidat", "üyelik ücret", "kart aidat"))
    masraf = any(
        word in blob for word in ("tahsis", "dosya masraf", "kredi masraf", "binde")
    ) or ("masraf" in blob and not aidat)
    cayma = any(word in blob for word in ("cayma", "14 gün", "ondört"))
    if cayma and not aidat and not masraf:
        return "cayma"
    if masraf and not aidat:
        return "masraf"
    if aidat:
        return "aidat"
    if cayma:
        return "cayma"
    if masraf:
        return "masraf"
    return "aidat"


def petition_query(topic: str, clause: str = "") -> str:
    kind = classify_petition(topic, clause)
    if kind == "cayma":
        return "tüketici kredisi cayma hakkı on dört gün 6502 MADDE 24"
    if kind == "masraf":
        return "kredi tahsis ücreti binde beş TCMB tebliğ MADDE 10 6502 MADDE 4"
    return (
        "kart çıkaran kuruluşlar yıllık üyelik aidatı sunmak zorundadır "
        "6502 MADDE 31 TCMB tebliğ MADDE 11"
    )


def build_petition_draft(
    topic: str,
    clause: str,
    bank: str,
    letter_date: str,
    lang: str = "tr",
    place: str = "................",
) -> dict:
    kind = classify_petition(topic, clause)
    spec = PETITION_KINDS[kind]
    refs = list(spec["refs"])
    if lang == "en":
        body = (
            f"{letter_date}\n\nTo the Consumer Arbitration Committee / {bank}\n\n"
            f"Subject: {spec['title']}\n\n{clause or topic}\n\n"
            "Legal basis: " + "; ".join(refs) + "\n\nDraft only. Not legal advice.\n"
        )
        disclaimer = "Draft only. Not legal advice."
    else:
        body = spec["body_tr"].format(
            date=letter_date,
            bank=bank or "........................",
            clause=clause or topic,
            place=place or "................",
        )
        disclaimer = (
            "Taslak metindir; hukuki tavsiye değildir. İmzalamadan önce resmi Resmî Gazete metnini kontrol edin."
        )
    return {
        "title": spec["title"] if lang != "en" else spec["title"],
        "body": body,
        "law_refs": refs,
        "disclaimer": disclaimer,
        "kind": kind,
    }
